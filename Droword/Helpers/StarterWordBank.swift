import Foundation

struct StarterWord {
    let word: String
    let translation: String
    let type: String
    let transcription: String?
    var example: String? = nil
    var explanation: String? = nil
    var breakdown: String? = nil
    var collocations: [String] = []
    var synonyms: [String] = []
    var antonyms: [String] = []
    var mnemonic: String? = nil
    var forms: [String] = []

    func asStoredWord(fromLanguage: String, toLanguage: String, tag: String? = nil, lockForms: Bool = false) -> StoredWord {
        let primary = example
        let complete = !(primary ?? "").isEmpty && !(explanation ?? "").isEmpty
        return StoredWord(
            word: word,
            type: type,
            translation: translation,
            example: primary,
            explanation: explanation,
            breakdown: breakdown,
            transcription: transcription,
            tag: tag,
            fromLanguage: fromLanguage,
            toLanguage: toLanguage,
            needsEnrichment: !complete,
            examples: primary.map { [$0] } ?? [],
            collocations: collocations,
            synonyms: synonyms,
            antonyms: antonyms,
            mnemonic: mnemonic,
            forms: forms,
            formsResolved: lockForms || !forms.isEmpty
        )
    }
}


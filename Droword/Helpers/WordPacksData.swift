// MARK: - Models

struct WordPack: Identifiable {
    let id: String
    let icon: String
    let colorKey: String // ThemeStore property name
    let titleKey: LocalizedStringKey
    let descriptionKey: LocalizedStringKey
    let wordCount: Int = 20
}

struct WordPackTracker {
    static func isCompleted(packID: String, learning: String, native: String) -> Bool {
        let key = "wordPack_\(packID)_\(learning)_\(native)_completed"
        return UserDefaults.standard.bool(forKey: key)
    }

    static func markCompleted(packID: String, learning: String, native: String) {
        let key = "wordPack_\(packID)_\(learning)_\(native)_completed"
        UserDefaults.standard.set(true, forKey: key)
    }
}

